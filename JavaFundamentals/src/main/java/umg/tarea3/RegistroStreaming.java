    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
    try {
            // Capturar datos en variables locales
            String nombre = txtNombreArtista.getText().trim();
            String pais = txtPaisOrigen.getText().trim();
            String oyentesTexto = txtOyentes.getText().trim();

            if (nombre.isEmpty() || pais.isEmpty() || oyentesTexto.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete todos los campos del Artista.");
                return;
            }

            int oyentes = Integer.parseInt(oyentesTexto);

            // Instanciar el objeto Artista y asignar valores con el operador punto (.)
            Artista a = new Artista();
            a.nombre = nombre;
            a.paisOrigen = pais;
            a.oyentesMensuales = oyentes;

            // Mostrar en pantalla usando .append() sin borrar lo anterior
            txtBitacora.append("=== NUEVO ARTISTA REGISTRADO ===\n");
            txtBitacora.append("Nombre: " + a.nombre + "\n");
            txtBitacora.append("País de Origen: " + a.paisOrigen + "\n");
            txtBitacora.append("Oyentes Mensuales: " + a.oyentesMensuales + "\n\n");

            // Limpiar campos
            txtNombreArtista.setText("");
            txtPaisOrigen.setText("");
            txtOyentes.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Los oyentes mensuales deben ser un número entero válido.");
        }
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // TODO add your handling code here:
    try {
            // Capturar datos en variables locales
            String titulo = txtTituloCancion.getText().trim();
            String duracionTexto = txtDuracion.getText().trim();
            String genero = txtGenero.getText().trim();
            String artista = txtArtistaCancion.getText().trim();

            if (titulo.isEmpty() || duracionTexto.isEmpty() || genero.isEmpty() || artista.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete todos los campos de la Canción.");
                return;
            }

            int duracion = Integer.parseInt(duracionTexto);

            // Instanciar el objeto Cancion y asignar valores con el operador punto (.)
            Cancion c = new Cancion();
            c.titulo = titulo;
            c.duracionSegundos = duracion;
            c.genero = genero;
            c.nombreArtista = artista;

            // Mostrar en pantalla usando .append()
            txtBitacora.append("--- NUEVA CANCIÓN REGISTRADA ---\n");
            txtBitacora.append("Título: " + c.titulo + "\n");
            txtBitacora.append("Duración: " + c.duracionSegundos + " segundos\n");
            txtBitacora.append("Género: " + c.genero + "\n");
            txtBitacora.append("Artista: " + c.nombreArtista + "\n\n");

            // Limpiar campos
            txtTituloCancion.setText("");
            txtDuracion.setText("");
            txtGenero.setText("");
            txtArtistaCancion.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "La duración en segundos debe ser un número entero válido.");
        }    
    }//GEN-LAST:event_btnCrearCancionActionPerformed

