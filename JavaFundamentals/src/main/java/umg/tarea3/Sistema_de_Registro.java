    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
    if (indice < 6) {
          try {
              double nota = Double.parseDouble(txtNota.getText().trim());

              if (nota < 0 || nota > 100) {
                  javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese una nota válida entre 0 y 100.");
                  return;
              }

              notas[indice] = nota;
              indice++;
              txtNota.setText("");
              txtNota.requestFocus();

              javax.swing.JOptionPane.showMessageDialog(this, "Nota " + indice + " de 6 agregada correctamente.");

          } catch (NumberFormatException e) {
              javax.swing.JOptionPane.showMessageDialog(this, "Error: Ingrese un valor numérico válido.");
          }
      } else {
          javax.swing.JOptionPane.showMessageDialog(this, "Ya se han ingresado las 6 notas máximas.");
      }    
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        // TODO add your handling code here:
    if (indice < 6) {
          javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar las 6 notas antes de generar el reporte. Faltan: " + (6 - indice));
          return;
      }

      int aprobados = 0;
      int reprobados = 0;
      double sumaTotal = 0;

      for (int i = 0; i < 6; i++) {
          sumaTotal += notas[i];
          if (notas[i] >= 61) {
              aprobados++;
          } else {
              reprobados++;
          }
      }

      double promedio = sumaTotal / 6.0;

      java.io.File carpetaTemp = new java.io.File("temp");
      if (!carpetaTemp.exists()) {
          carpetaTemp.mkdirs();
      }

      java.io.File archivo = new java.io.File(carpetaTemp, "abigail_reporte_notas.txt");

      try (java.io.FileWriter fw = new java.io.FileWriter(archivo);
           java.io.PrintWriter pw = new java.io.PrintWriter(fw)) {

          pw.println("Reporte de Notas");
          pw.println("Aprobados: " + aprobados);
          pw.println("Reprobados: " + reprobados);
          pw.println("Promedio de Notas: " + (int)promedio);

          javax.swing.JOptionPane.showMessageDialog(this, "¡Reporte generado exitosamente en la carpeta temp!");

      } catch (java.io.IOException e) {
          javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el archivo: " + e.getMessage());
      }    
    }//GEN-LAST:event_btnGenerarActionPerformed

