    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
    if (indice < 5) {
            String nombre = txtNombre.getText().trim();

            if (nombre.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese el nombre del pasajero.");
                return;
            }

            pasajeros[indice] = nombre;
            indice++;

            // Reflejar en el área de texto
            txtLista.append(indice + ". " + nombre + "\n");

            txtNombre.setText("");
            txtNombre.requestFocus();

            javax.swing.JOptionPane.showMessageDialog(this, "Pasajero " + indice + " de 5 registrado.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Ya se han registrado los 5 pasajeros.");
        }    // TODO add your handling code here:
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
    if (indice < 5) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe registrar los 5 pasajeros antes de exportar. Faltan: " + (5 - indice));
            return;
        }

        java.io.File carpetaTemp = new java.io.File("temp");
        if (!carpetaTemp.exists()) {
            carpetaTemp.mkdirs();
        }

        java.io.File archivo = new java.io.File(carpetaTemp, "abigail_manifiesto.txt");

        try (java.io.FileWriter fw = new java.io.FileWriter(archivo);
             java.io.PrintWriter pw = new java.io.PrintWriter(fw)) {

            pw.println("Manifiesto Oficial de Vuelo");
            for (int i = 0; i < 5; i++) {
                pw.println((i + 1) + ". " + pasajeros[i]);
            }

            javax.swing.JOptionPane.showMessageDialog(this, "¡Manifiesto exportado exitosamente a la carpeta temp!");

        } catch (java.io.IOException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el manifiesto: " + e.getMessage());
        }    // TODO add your handling code here:
    }//GEN-LAST:event_btnExportarActionPerformed

