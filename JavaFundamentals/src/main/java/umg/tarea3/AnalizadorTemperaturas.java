    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
    // TODO add your handling code here:
        java.io.File archivo = new java.io.File("temp/temperaturas.txt");
             
        if (!archivo.exists()) {
            javax.swing.JOptionPane.showMessageDialog(this, "El archivo temp/temperaturas.txt no existe. Por favor créelo primero.");
            return;
        }

        try (java.util.Scanner scanner = new java.util.Scanner(archivo)) {
            int i = 0;
            while (scanner.hasNextLine() && i < 6) {
                String linea = scanner.nextLine().trim();
                if (!linea.isEmpty()) {
                    temperaturas[i] = Double.parseDouble(linea);
                    i++;
                }
            }

            if (i < 6) {
                javax.swing.JOptionPane.showMessageDialog(this, "Advertencia: El archivo tenía menos de 6 registros de temperatura.");
            } else {
                datosCargados = true;
                javax.swing.JOptionPane.showMessageDialog(this, "¡Los datos fueron cargados en memoria exitosamente!");
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al leer el archivo: " + e.getMessage());
        }    
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
        if (!datosCargados) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debe presionar el botón 'Cargar Datos'.");
            return;
        }

        double suma = 0;
        int calidos = 0;
        int frescos = 0;

        for (int i = 0; i < 6; i++) {
            suma += temperaturas[i];
            if (temperaturas[i] >= 25.0) {
                calidos++;
            } else {
                frescos++;
            }
        }

        double promedio = suma / 6.0;

        // Construir el reporte con el formato exacto requerido
        StringBuilder reporte = new StringBuilder();
        reporte.append("Análisis Climático\n\n");
        reporte.append("---------------------\n\n");
        reporte.append("Promedio de Temperatura: ").append(String.format("%.1f", promedio)).append("\n\n");
        reporte.append("Días Cálidos (>= 25°): ").append(calidos).append("\n\n");
        reporte.append("Días Frescos (< 25°): ").append(frescos);

        txtResultado.setText(reporte.toString());
    }//GEN-LAST:event_btnCalcularActionPerformed

