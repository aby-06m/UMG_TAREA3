    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
    String busqueda = txtBuscar.getText().trim();

        if (busqueda.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese el título del álbum a buscar.");
            return;
        }

        boolean encontrado = false;
        for (int i = 0; i < 5; i++) {
            if (titulos[i] != null && titulos[i].equalsIgnoreCase(busqueda)) {
                lblAnioEncontrado.setText("Año Encontrado: " + anios[i]);
                txtNuevoAnio.setText(anios[i]);
                encontrado = true;
                break;
            }
        }

        if (!encontrado) {
            lblAnioEncontrado.setText("Año Encontrado: No hallado");
            txtNuevoAnio.setText("");
            javax.swing.JOptionPane.showMessageDialog(this, "El disco no fue encontrado en la biblioteca.");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
    String busqueda = txtBuscar.getText().trim();
        String nuevoAnio = txtNuevoAnio.getText().trim();

        if (busqueda.isEmpty() || nuevoAnio.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe buscar un disco e ingresar el nuevo año.");
            return;
        }

        int indiceEncontrado = -1;
        for (int i = 0; i < 5; i++) {
            if (titulos[i] != null && titulos[i].equalsIgnoreCase(busqueda)) {
                indiceEncontrado = i;
                break;
            }
        }

        if (indiceEncontrado != -1) {
            // Actualizar arreglo en memoria
            anios[indiceEncontrado] = nuevoAnio;

            // Sobrescribir el archivo CSV
            java.io.File archivo = new java.io.File("temp/discos.csv");
            try (java.io.FileWriter fw = new java.io.FileWriter(archivo, false); // false para sobrescribir
                 java.io.PrintWriter pw = new java.io.PrintWriter(fw)) {

                for (int i = 0; i < 5; i++) {
                    if (titulos[i] != null) {
                        pw.println(titulos[i] + "," + anios[i]);
                    }
                }

                lblAnioEncontrado.setText("Año Encontrado: " + nuevoAnio);
                javax.swing.JOptionPane.showMessageDialog(this, "¡Registro actualizado y guardado en discos.csv exitosamente!");

            } catch (java.io.IOException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error al sobrescribir el archivo: " + e.getMessage());
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se puede actualizar porque el disco no existe.");
        }    
    }//GEN-LAST:event_btnActualizarActionPerformed

