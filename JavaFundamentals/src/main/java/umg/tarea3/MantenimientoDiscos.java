private void cargarDatosAutomatico() {
        java.io.File archivo = new java.io.File("temp/discos.csv");
        if (!archivo.exists()) {
            javax.swing.JOptionPane.showMessageDialog(this, "El archivo temp/discos.csv no existe.");
            return;
        }

        try (java.util.Scanner sc = new java.util.Scanner(archivo)) {
            int i = 0;
            while (sc.hasNextLine() && i < 5) {
                String linea = sc.nextLine().trim();
                if (!linea.isEmpty()) {
                    String[] partes = linea.split(",");
                    if (partes.length >= 2) {
                        titulos[i] = partes[0].trim();
                        anios[i] = partes[1].trim();
                        i++;
                    }
                }
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar discos: " + e.getMessage());
        }
    }
               
    

