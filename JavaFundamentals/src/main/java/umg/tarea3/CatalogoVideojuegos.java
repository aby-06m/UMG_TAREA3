    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
      // Validar que la lista tenga elementos
        if (catalogo.size() > 0) {
            int ultimoIndice = catalogo.size() - 1;
            Videojuego eliminado = catalogo.remove(ultimoIndice);

            javax.swing.JOptionPane.showMessageDialog(this, "Se ha eliminado el último juego: " + eliminado.titulo);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No hay juegos en el catálogo para eliminar.");
        }  
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        try {
            String titulo = txtTitulo.getText().trim();
            String consola = txtConsola.getText().trim();
            String anioTexto = txtAnio.getText().trim();

            if (titulo.isEmpty() || consola.isEmpty() || anioTexto.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.");
                return;
            }

            int anio = Integer.parseInt(anioTexto);

            // Instanciar pasando los parámetros al constructor y agregar al ArrayList
            Videojuego juego = new Videojuego(titulo, consola, anio);
            catalogo.add(juego);

            javax.swing.JOptionPane.showMessageDialog(this, "¡Juego agregado exitosamente al catálogo!");

            // Limpiar cajas de texto
            txtTitulo.setText("");
            txtConsola.setText("");
            txtAnio.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El año de lanzamiento debe ser un número entero válido.");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:
        txtInventario.setText(""); // Limpiar área de texto

        if (catalogo.isEmpty()) {
            txtInventario.append("El catálogo se encuentra vacío actualmente.\n");
            return;
        }

        txtInventario.append("=== CATÁLOGO DE VIDEOJUEGOS ===\n\n");

        // Recorrer el ArrayList con un ciclo for usando .get(i)
        for (int i = 0; i < catalogo.size(); i++) {
            Videojuego v = catalogo.get(i);
            txtInventario.append((i + 1) + ". Título: " + v.titulo + " | Consola: " + v.consola + " | Año: " + v.anioLanzamiento + "\n");
        }

        // Mostrar total utilizando .size()
        txtInventario.append("\n-----------------------------------\n");
        txtInventario.append("Total de juegos registrados: " + catalogo.size() + "\n");
    }//GEN-LAST:event_btnMostrarActionPerformed

